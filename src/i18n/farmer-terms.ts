export function farmerTerm(locale: string, term: string): string | undefined {
  const index = keys.indexOf(term as Term);
  const language = isLanguageCode(locale) ? locale : "en";
  return index < 0
    ? farmerScreenLabel(language, term)
    : farmerTerms[language][index];
}

