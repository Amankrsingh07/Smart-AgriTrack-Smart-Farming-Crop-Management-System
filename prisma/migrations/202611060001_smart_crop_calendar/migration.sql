CREATE TABLE `CropCalendar` (
  `id` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `farmId` VARCHAR(191) NOT NULL,
  `cropCycleId` VARCHAR(191) NOT NULL,
  `cropId` VARCHAR(191) NOT NULL,
  `cropVariety` VARCHAR(120) NULL,
  `state` VARCHAR(100) NOT NULL,
  `district` VARCHAR(100) NOT NULL,
  `sowingDate` DATE NOT NULL,
  `landArea` DECIMAL(10,2) NOT NULL,
  `areaUnit` VARCHAR(16) NOT NULL,
  `soilType` VARCHAR(80) NOT NULL,
  `irrigationMethod` VARCHAR(80) NOT NULL,
  `estimatedHarvestDate` DATE NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  `datasetVersion` VARCHAR(40) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  INDEX `CropCalendar_userId_status_sowingDate_idx` (`userId`, `status`, `sowingDate`),
  INDEX `CropCalendar_farmId_sowingDate_idx` (`farmId`, `sowingDate`),
  UNIQUE INDEX `CropCalendar_cropCycleId_key` (`cropCycleId`),
  PRIMARY KEY (`id`),
  CONSTRAINT `CropCalendar_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `CropCalendar_farmId_fkey` FOREIGN KEY (`farmId`) REFERENCES `Farm` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `CropCalendar_cropId_fkey` FOREIGN KEY (`cropId`) REFERENCES `Crop` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `CropCalendar_cropCycleId_fkey` FOREIGN KEY (`cropCycleId`) REFERENCES `CropCycle` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `CropCalendarActivity` (
  `id` VARCHAR(191) NOT NULL,
  `calendarId` VARCHAR(191) NOT NULL,
  `activityKey` VARCHAR(120) NOT NULL,
  `activityName` VARCHAR(160) NOT NULL,
  `activityType` VARCHAR(32) NOT NULL,
  `growthStage` VARCHAR(80) NULL,
  `scheduledDate` DATE NOT NULL,
  `actualCompletionDate` DATETIME(3) NULL,
  `description` TEXT NOT NULL,
  `recommendation` TEXT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  `isWeatherAdjusted` BOOLEAN NOT NULL DEFAULT false,
  `isManuallyModified` BOOLEAN NOT NULL DEFAULT false,
  `notes` VARCHAR(500) NULL,
  `source` VARCHAR(255) NULL,
  `sourceUrl` TEXT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `CropCalendarActivity_calendarId_activityKey_key` (`calendarId`, `activityKey`),
  INDEX `CropCalendarActivity_calendarId_scheduledDate_status_idx` (`calendarId`, `scheduledDate`, `status`),
  PRIMARY KEY (`id`),
  CONSTRAINT `CropCalendarActivity_calendarId_fkey` FOREIGN KEY (`calendarId`) REFERENCES `CropCalendar` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `CropCalendarNotification` (
  `id` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `activityId` VARCHAR(191) NOT NULL,
  `notificationDate` DATE NOT NULL,
  `message` VARCHAR(500) NOT NULL,
  `isRead` BOOLEAN NOT NULL DEFAULT false,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `CropCalendarNotification_activityId_notificationDate_key` (`activityId`, `notificationDate`),
  INDEX `CropCalendarNotification_userId_isRead_notificationDate_idx` (`userId`, `isRead`, `notificationDate`),
  PRIMARY KEY (`id`),
  CONSTRAINT `CropCalendarNotification_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `CropCalendarNotification_activityId_fkey` FOREIGN KEY (`activityId`) REFERENCES `CropCalendarActivity` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
